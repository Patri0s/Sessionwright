[MarkupExtensionReturnType(typeof(string))]
public sealed class LExtension(string key) : MarkupExtension
{
    public override object ProvideValue(IServiceProvider serviceProvider) => Loc.Get(key);
}

/// <summary>ComboBox item with a value and a localized label.</summary>
public sealed record Choice(object? Value, string Text)
{
    public override string ToString() => Text;

    public static object? Get(ComboBox box) => (box.SelectedItem as Choice)?.Value;

    public static void Select(ComboBox box, object? value) =>
        box.SelectedItem = box.Items.OfType<Choice>().FirstOrDefault(c => Equals(c.Value, value)) ?? box.Items.OfType<Choice>().FirstOrDefault();
}
