    internal static bool Polish => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "pl";

    public static string Get(string key) => Strings.TryGetValue(key, out var s) ? (Polish ? s.Pl : s.En) : key;

    public static string Format(string key, params object?[] args) => string.Format(Get(key), args);

    /// <summary>"5 min ago", "3 h ago", "yesterday", "4 d ago".</summary>
    public static string Ago(DateTime then, DateTime now)
    {
        var span = now - then;
        if (span.TotalMinutes < 1) return Get("AgoNow");
        if (span.TotalHours < 1) return Format("AgoMinutes", (int)span.TotalMinutes);
        if (span.TotalDays < 1) return Format("AgoHours", (int)span.TotalHours);
        return (int)span.TotalDays == 1 ? Get("AgoDay") : Format("AgoDays", (int)span.TotalDays);
    }

